from tests.conftest import MINI_SCHEMA


class TestBuildClassMap:
    def test_maps_uid_to_caption_sorted_by_uid(self):
        schema = {"classes": {"b": {"uid": 20, "caption": "Bee"}, "a": {"uid": 10, "caption": "Ay"}}}
        result = gcm.build_class_map(schema)
        assert result == {10: "Ay", 20: "Bee"}
        assert list(result) == [10, 20]

    def test_uid_zero_is_a_valid_class(self):
        assert gcm.build_class_map({"classes": {"base": {"uid": 0, "caption": "Base"}}}) == {0: "Base"}

    def test_skips_classes_missing_a_uid_or_caption(self, capsys):
        schema = {"classes": {
            "ok": {"uid": 1, "caption": "Ok"},
            "no_uid": {"caption": "X"},
            "no_caption": {"uid": 2},
            "blank_caption": {"uid": 3, "caption": ""},
        }}
        assert gcm.build_class_map(schema) == {1: "Ok"}
        err = capsys.readouterr().err
        assert all(name in err for name in ("no_uid", "no_caption", "blank_caption"))

    def test_conflicting_duplicate_uids_exit(self):
        schema = {"classes": {"a": {"uid": 1, "caption": "A"}, "b": {"uid": 1, "caption": "B"}}}
        with pytest.raises(SystemExit, match="duplicate class_uid 1"):
            gcm.build_class_map(schema)

    def test_identical_duplicates_are_tolerated(self):
        schema = {"classes": {"a": {"uid": 1, "caption": "A"}, "b": {"uid": 1, "caption": "A"}}}
        assert gcm.build_class_map(schema) == {1: "A"}

    @pytest.mark.parametrize("schema", [{}, {"classes": {}}])
    def test_schema_without_classes_exits(self, schema):
        with pytest.raises(SystemExit, match="no 'classes'"):
            gcm.build_class_map(schema)


class TestLoadSchema:
    def test_json(self, tmp_path):
        path = tmp_path / "s.json"
        path.write_text(json.dumps(MINI_SCHEMA))
        assert gcm.load_schema(path)["classes"]["widget"]["uid"] == 1

    @pytest.mark.parametrize("suffix", [".yaml", ".yml"])
    def test_yaml(self, tmp_path, suffix):
        path = tmp_path / f"s{suffix}"
        path.write_text(yaml.safe_dump(MINI_SCHEMA))
        assert gcm.load_schema(path)["classes"]["gadget"]["uid"] == 2


class TestCommandLine:
    def run(self, *args):
        return subprocess.run([sys.executable, "-m", "scripts.generate_class_map", *args], cwd=ROOT,
                              capture_output=True, text=True)

    @pytest.fixture
    def schema_file(self, tmp_path):
        path = tmp_path / "schema.json"
        path.write_text(json.dumps(MINI_SCHEMA))
        return path

    def test_writes_the_output_file_with_a_generated_header(self, schema_file, tmp_path):
        out = tmp_path / "out" / "class_map.yaml"
        out.parent.mkdir()
        result = self.run(str(schema_file), "-o", str(out))
        assert result.returncode == 0
        text = out.read_text()
        assert text.startswith("# This file is generated by scripts/generate_class_map.py")
        assert "schema.json" in text.splitlines()[0]
        assert "Do not edit it manually" in text.splitlines()[1]
        assert yaml.safe_load(text) == {"classes": {1: "Widget", 2: "Gadget"}}
        assert "wrote 2 classes" in result.stderr

    def test_dash_writes_to_stdout(self, schema_file):
        result = self.run(str(schema_file), "-o", "-")
        assert result.returncode == 0
        assert yaml.safe_load(result.stdout) == {"classes": {1: "Widget", 2: "Gadget"}}

    def test_bad_schema_fails(self, tmp_path):
        bad = tmp_path / "bad.json"
        bad.write_text(json.dumps({"classes": {}}))
        result = self.run(str(bad), "-o", "-")
        assert result.returncode != 0
        assert "no 'classes'" in result.stderr


class TestCommittedClassMap:
    def test_matches_what_the_generator_produces_from_the_real_schema(self):
        """Drift check: validate-and-compile-schema regenerates class_map.yaml, but
        complex_mappings.py reads the committed copy at import time, so a stale file means the
        repo and the schema disagree.
        If this fails, run `python -m scripts.generate_class_map` and commit the result."""
        import scripts.common as pc
        generated = gcm.build_class_map(gcm.load_schema(pc.SCHEMA_PATH))
        committed = yaml.safe_load(pc.CLASS_MAP_PATH.read_text())["classes"]
        assert committed == generated
